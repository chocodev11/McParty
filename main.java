// Khai báo lớp chính của chương trình; tên lớp viết thường để khớp với tên tệp main.java.
public class main { // Mở phần định nghĩa của lớp main.

    // Khai báo phương thức main; đây là điểm bắt đầu khi chương trình được chạy.
    public static void main(String[] args) { // Nhận các đối số được truyền từ dòng lệnh.

        // In dòng chữ "Hello, World!" ra màn hình console.
        System.out.println("Hello, World!"); // println tự động xuống dòng sau khi in.
    } // Kết thúc phương thức main.
} // Kết thúc lớp main.
